public class 算術運算 {
    public static void main(String A[])
    {
        int a = 155;
        int b = 9;
        float g;
        g = a/b ;
        System.out.println("g = a/b ; , g="+g);
        g = (float)a/b;
        System.out.println("(float)a/b , g="+g);
        g = (int)(a/9.0);
        System.out.println("(int)a/9.0 , g="+g);

    }
    
}
